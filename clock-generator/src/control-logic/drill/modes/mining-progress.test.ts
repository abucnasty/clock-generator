describe("a drill's bonus bar near a whole item", () => {
    it.each(PROBE)("bar %s + %s at mining time %s gives the game's %s and %s items", (bar, step, mining_time, game_bar, game_items) => {
        const next = bonusBarTick(bar, step, mining_time);
        expect(next.items).toBe(game_items);
        expect(next.bar).toBeCloseTo(game_bar, 12);
    });

    it("drops a remainder under 0.001 after an item and makes the item 0.0001 short of one, as the drills' recordings show", () => {
        // +82% at 0.0875 a tick: the 223rd tick's 16.00025 keeps nothing, so the bar repeats every 223 ticks
        expect(bonusBarTick(0.9284999999999982, 0.07175, 1)).toEqual({ bar: 0, items: 1 });
        // +399,990% at 0.25 a tick: a sum 2.5e-8 short of a thousand makes the thousandth item
        expect(bonusBarTick(0.02499997521158548, 999.9749999993644, 1)).toEqual({ bar: 0, items: 1000 });
        // +70% at 0.25 a tick: 1.0000000000000002 keeps nothing
        expect(bonusBarTick(0.8250000000000002, 0.175, 1)).toEqual({ bar: 0, items: 1 });
        // and carries what is not near a whole: 0.0017 above, 0.0017 below
        expect(bonusBarTick(0.9733333333333314, 0.028333333333333332, 1).bar).toBeCloseTo(0.0016666666666647, 15);
        expect(bonusBarTick(0.97, 0.028333333333333332, 1)).toEqual({ bar: 0.9983333333333333, items: 0 });
    });

    it("keeps a bar under 0.001 that made no item", () => {
        let bar = 0;
        for (let tick = 1; tick <= 4; tick++) {
            bar = bonusBarTick(bar, 0.0005, 1).bar;
            expect(bar).toBeCloseTo(0.0005 * tick, 15);
        }
    });
});

describe("a drill's bars in the game's units", () => {
    /** A big mining drill with 4 legendary speed modules 3 (0.25 a tick) on `resource`, at `productivity` percent */
    function progressOn(resource: string, productivity: number) {
        const config = ConfigSchema.parse({ target_output: { recipe: "iron-gear-wheel", items_per_second: 1, copies: 1 },
            machines: [{ id: 1, recipe: "iron-gear-wheel", crafting_speed: 1, productivity: 0 }], belts: [], inserters: [],
            drills: { configs: [{ id: 1, type: "big-mining-drill", mined_item_name: resource, speed_bonus: 5, productivity, target: { type: "chest", id: 1 } }] },
            chests: [{ type: "car", id: 1 }] });
        return new MiningProgress(SimulationContext.fromConfig(config).drills[0].drill_state.drill);
    }

    it("run from 0 to the resource's mining time: scrap (0.5) wraps every 2 ticks", () => {
        const progress = progressOn("scrap", 0);
        expect([progress.mine(), progress.mining_progress]).toEqual([0, 0.25]);
        expect([progress.mine(), progress.mining_progress]).toEqual([1, 0]);
    });

    it("keep the fraction of a mining time when the bonus bar makes 2 or more items: on scrap, an item more", () => {
        // +390% on scrap: the bonus bar moves 0.975 a tick (1.95 mining times of 0.5)
        const progress = progressOn("scrap", 390);
        // 0.975: one item, 0.475 left
        expect(progress.mine()).toBe(1);
        expect(progress.bonus_progress).toBeCloseTo(0.475, 12);
        // the mining bar's item, and 1.45 = 2.9 mining times: 2 items and 0.9 kept, which is a mining time (0.5) and more:
        // one more item and 0.4 left, where 2.9 mining times would keep 0.45
        expect(progress.mine()).toBe(1 + 3);
        expect(progress.bonus_progress).toBeCloseTo(0.4, 12);
    });
});

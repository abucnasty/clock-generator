import fs from "node:fs";
import path from "node:path";
import {expect, test} from "vitest";
import {generateClockAlternatives} from "./generate-blueprint";
import {loadConfigFromFile} from "../config/loader";
import {ConfigPaths} from "../config/config-paths";
import {clockHash} from "../../tests/game/builds/clock-controls";
import {scaffoldClockPins} from "../../tests/game/builds/scaffold-recordings-clock-pins";

// the clocks the values of three scaffold-recordings builds were seen on (scaffold-recordings.game.test.ts)
const quiet = {log() {}, info() {}, warn() {}, error() {}, debug() {}};

// Two of the three builds are generated by a test of their own, from the same config: the pin of each is checked there,
// on that generation (expectPinnedScaffoldClock), and not by generating the build a second time here.
const checkedWithAnotherGeneration: Record<string, string> = {
    "agricultural science": "agricultural-science.generation.test.ts",
    "agricultural science (belts are backed up)": "clock-belt.generation.test.ts",
};

for (const [name, pin] of Object.entries(scaffoldClockPins)) {
    const checkedIn = checkedWithAnotherGeneration[name];
    if (checkedIn) {
        test(`scaffold recordings: ${name}, on the generation of ${checkedIn}`, () => {
            expect(fs.readFileSync(path.join(__dirname, checkedIn), "utf8"), `${checkedIn} no longer checks the pin of ${name}`)
                .toContain(`expectPinnedScaffoldClock(${JSON.stringify(name)},`);
        });
        continue;
    }
    test(`scaffold recordings: ${name}`, async () => {
        const loaded = await loadConfigFromFile((ConfigPaths as Record<string, string>)[pin.config]);
        const config = pin.backed_up_belts ? {...loaded, overrides: {...loaded.overrides, backed_up_belts: true}} : loaded;
        const generated = generateClockAlternatives(config, {logger: quiet});
        const selected = generated.alternatives[generated.selected_index];
        expect(clockHash(selected.result.subtick ?? selected.result), "the selected clock is not the one this build's recorded values belong to")
            .toBe(pin.clock_sha256);
    });
}
